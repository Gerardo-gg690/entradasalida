create extension if not exists pgcrypto;

create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  name text not null,
  dept text default '',
  pin_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  work_date date not null,
  clock_in timestamptz,
  clock_out timestamptz,
  unique(employee_id, work_date)
);
create table if not exists public.app_config (
  id int primary key default 1 check(id=1), salary numeric not null default 408,
  half_salary numeric not null default 204, paid_days numeric not null default 30,
  normal_hours numeric not null default 8, extra_rate numeric not null default 3
);
insert into public.app_config(id) values(1) on conflict do nothing;
create table if not exists public.admin_account (
  id int primary key default 1 check(id=1), username text unique not null, password_hash text not null
);
create table if not exists public.admin_sessions (
  token uuid primary key default gen_random_uuid(), expires_at timestamptz not null default now()+interval '12 hours'
);

alter table public.employees enable row level security;
alter table public.attendance enable row level security;
alter table public.app_config enable row level security;
alter table public.admin_account enable row level security;
alter table public.admin_sessions enable row level security;
revoke all on public.employees, public.attendance, public.app_config, public.admin_account, public.admin_sessions from anon, authenticated;

create or replace function public.list_employees() returns table(id bigint,name text,dept text,status text,clock_in timestamptz,clock_out timestamptz)
language sql security definer set search_path=public as $$
 select e.id,e.name,e.dept,
 case when a.clock_in is null then 'none' when a.clock_out is null then 'working' else 'done' end,
 a.clock_in,a.clock_out from employees e left join attendance a on a.employee_id=e.id and a.work_date=current_date where e.active=true order by e.name;
$$;

create or replace function public.mark_attendance(p_employee_id bigint,p_pin text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare e employees; a attendance; typ text;
begin
 select * into e from employees where id=p_employee_id and active=true;
 if e.id is null or crypt(p_pin,e.pin_hash)<>e.pin_hash then raise exception 'PIN incorrecto'; end if;
 select * into a from attendance where employee_id=p_employee_id and work_date=current_date for update;
 if a.id is null then
   insert into attendance(employee_id,work_date,clock_in) values(p_employee_id,current_date,now()) returning * into a; typ:='Entrada';
 elsif a.clock_out is null then
   update attendance set clock_out=now() where id=a.id returning * into a; typ:='Salida';
 else raise exception 'Turno ya completado'; end if;
 return jsonb_build_object('type',typ,'time',coalesce(a.clock_out,a.clock_in));
end $$;

create or replace function public.admin_exists() returns boolean language sql security definer set search_path=public as $$select exists(select 1 from admin_account where id=1)$$;
create or replace function public.admin_create(p_username text,p_password text) returns uuid
language plpgsql security definer set search_path=public as $$declare t uuid; begin
 if exists(select 1 from admin_account) then raise exception 'La cuenta administradora ya existe'; end if;
 if length(trim(p_username))<3 or length(p_password)<6 then raise exception 'Credenciales no válidas'; end if;
 insert into admin_account(id,username,password_hash) values(1,trim(p_username),crypt(p_password,gen_salt('bf')));
 insert into admin_sessions default values returning token into t; return t; end $$;
create or replace function public.admin_login(p_username text,p_password text) returns uuid
language plpgsql security definer set search_path=public as $$declare a admin_account;t uuid;begin
 select * into a from admin_account where username=p_username;
 if a.id is null or crypt(p_password,a.password_hash)<>a.password_hash then raise exception 'Usuario o contraseña incorrectos'; end if;
 delete from admin_sessions where expires_at<now(); insert into admin_sessions default values returning token into t; return t; end $$;
create or replace function public.is_admin_token(p_token uuid) returns boolean language sql security definer set search_path=public as $$select exists(select 1 from admin_sessions where token=p_token and expires_at>now())$$;

create or replace function public.admin_add_employee(p_token uuid,p_name text,p_dept text,p_pin text) returns void
language plpgsql security definer set search_path=public as $$begin
 if not is_admin_token(p_token) then raise exception 'Sesión no válida'; end if;
 if length(trim(p_name))<2 or p_pin !~ '^[0-9]{4,6}$' then raise exception 'Datos no válidos'; end if;
 insert into employees(name,dept,pin_hash) values(trim(p_name),coalesce(trim(p_dept),''),crypt(p_pin,gen_salt('bf'))); end $$;
create or replace function public.admin_remove_employee(p_token uuid,p_id bigint) returns void language plpgsql security definer set search_path=public as $$begin if not is_admin_token(p_token) then raise exception 'Sesión no válida';end if; delete from employees where id=p_id;end$$;
create or replace function public.admin_set_config(p_token uuid,p_salary numeric,p_half_salary numeric,p_paid_days numeric,p_normal_hours numeric,p_extra_rate numeric) returns void
language plpgsql security definer set search_path=public as $$begin if not is_admin_token(p_token) then raise exception 'Sesión no válida';end if; update app_config set salary=p_salary,half_salary=p_half_salary,paid_days=p_paid_days,normal_hours=p_normal_hours,extra_rate=p_extra_rate where id=1;end$$;
create or replace function public.admin_day(p_token uuid,p_date date) returns jsonb
language plpgsql security definer set search_path=public as $$declare result jsonb;begin
 if not is_admin_token(p_token) then raise exception 'Sesión no válida';end if;
 select jsonb_build_object('config',(select to_jsonb(c) from app_config c where id=1),'employees',coalesce((select jsonb_agg(to_jsonb(x)) from (select e.id,e.name,e.dept,a.clock_in,a.clock_out from employees e left join attendance a on a.employee_id=e.id and a.work_date=p_date where e.active order by e.name)x),'[]'::jsonb)) into result;return result;end$$;
create or replace function public.admin_fortnight(p_token uuid,p_employee_id bigint,p_date date) returns jsonb
language plpgsql security definer set search_path=public as $$declare s date;f date;r jsonb;begin
 if not is_admin_token(p_token) then raise exception 'Sesión no válida';end if;
 s:=date_trunc('month',p_date)::date + case when extract(day from p_date)<=15 then 0 else 15 end;
 f:=case when extract(day from p_date)<=15 then date_trunc('month',p_date)::date+14 else (date_trunc('month',p_date)+interval '1 month-1 day')::date end;
 select jsonb_build_object('employee',(select to_jsonb(x) from (select id,name,dept from employees where id=p_employee_id)x),'config',(select to_jsonb(c) from app_config c where id=1),'start',s,'end',f,'records',coalesce((select jsonb_agg(to_jsonb(a) order by work_date) from attendance a where employee_id=p_employee_id and work_date between s and f),'[]'::jsonb)) into r;return r;end$$;

